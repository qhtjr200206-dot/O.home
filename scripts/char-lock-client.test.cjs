const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const path = require('node:path');
const file = path.join(__dirname, '../src/lib/charLockClient.ts');
assert.ok(fs.existsSync(file), 'character lock client must exist');
const mod = new Module(file, module); mod.filename = file; mod.paths = module.paths;
mod._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020}}).outputText, file);
const client = mod.exports;
(async () => {
  let request;
  global.fetch = async (url, options) => { request = {url, options}; return {ok:true, json: async () => ({lockVersion:'v1',char:{id:'c1', name:'name', basicHtml:'secret', lockHash:'must-not-leak'}})}; };
  const result = await client.openCharacter('c1', 'pass', 'token-for-test');
  assert.equal(request.options.headers.Authorization, 'Bearer token-for-test');
  assert.equal(result.ok, true);
  assert.equal(request.url, '/api/chars/unlock');
  assert.deepEqual(JSON.parse(request.options.body), {id:'c1', password:'pass'});
  assert.equal(client.openedCharacter('c1').basicHtml, 'secret');
  assert.equal(client.openedCharacter('c1').lockHash, undefined);
  client.clearOpenedCharacters();
  assert.equal(client.openedCharacter('c1'), undefined);
  const reopened = await client.openCharacter('c1', 'pass');
  assert.equal(reopened.ok, true);
  let finish;
  global.fetch = () => new Promise(resolve => {finish = resolve;});
  const pending = client.openCharacter('pending', 'pass');
  client.clearOpenedCharacters();
  finish({ok:true, json: async () => ({char:{id:'pending', basicHtml:'stale'}})});
  assert.equal((await pending).ok, false);
  assert.equal(client.openedCharacter('pending'), undefined);
  global.fetch = async () => ({ok:true, json: async () => ({lockVersion:'v1',char:{id:'c1', name:'name', basicHtml:'secret'}})});
  await client.openCharacter('c1', 'pass');
  const merged = client.mergeCharacterReads([{id:'c1', name:'cover', locked:true, lockVersion:'v1', visibility:'public'}, {id:'c3', name:'third', locked:true}], [{id:'c3', character:{id:'c3', basicHtml:'admin secret'}, lockHash:'hidden'}]);
  assert.equal(merged[0].basicHtml, 'secret');
  assert.equal(merged[0].name, 'cover');
  assert.equal(merged[0].lockHash, undefined);
  assert.equal(merged[1].basicHtml, 'admin secret');
  assert.equal(merged[1].lockHash, undefined);
  const changed = client.mergeCharacterReads([{id:'c1', locked:true, lockVersion:'v2'}], []);
  assert.equal(changed[0].lockStub, true);
  assert.equal(client.openedCharacter('c1'), undefined);
  await client.openCharacter('c1', 'pass');
  assert.equal(client.mergeCharacterReads([{id:'c1', locked:true}], [])[0].lockStub, true);
  assert.equal(client.openedCharacter('c1'), undefined);
  assert.equal(client.mergeCharacterReads([{id:'c4', locked:true}], [], true)[0].lockSecretError, true);
  assert.equal(client.mergeCharacterReads([{id:'c4', locked:true}], [])[0].lockStub, true);
  assert.throws(() => client.ensureNoLockedWrites([{id:'c1', locked:true, basicHtml:'secret'}], [{id:'c1', locked:true, basicHtml:'changed'}]));
  assert.deepEqual(client.charactersWithEditableGrants([{id:'a',locked:true,grants:[{level:'edit'}]},{id:'b',grants:[{level:'edit'}]}]).map(c=>c.id), ['b']);
  assert.throws(() => client.ensureNoLockedWrites([{id:'c1', locked:true}], []));
  assert.doesNotThrow(() => client.ensureNoLockedWrites([{id:'c1', locked:true}], [{id:'c1', locked:true}]));
  global.fetch = async () => ({ok:false, status:401, json: async () => ({error:'wrong'})});
  assert.equal((await client.openCharacter('c2', 'bad')).ok, false);
  assert.equal(client.openedCharacter('c2'), undefined);
  console.log('character lock client tests passed');
})().catch(e => { console.error(e); process.exitCode = 1; });
